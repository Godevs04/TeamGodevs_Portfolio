import studentProjects from './student-projects.json' with { type: 'json' };

/**
 * Server-side source of truth for fixed prices (INR). Order amounts for catalog
 * items are always computed here — never trusted from the browser.
 * Keep in sync with PRICE_TIERS in web/src/components/student-projects/data.ts.
 */
export const STUDENT_PROJECT_PRICE_TIERS = {
  1: 2499,
  2: 3499,
  3: 4499,
  4: 5999,
} as const;

export type StudentProjectTier = keyof typeof STUDENT_PROJECT_PRICE_TIERS;

export type StudentProjectEntry = { code: string; title: string; tier: StudentProjectTier };

/** Generated by `npm run catalog:sync` from the web catalog. */
const STUDENT_PROJECTS = studentProjects as Record<string, StudentProjectEntry>;

export function findStudentProject(id: string): StudentProjectEntry | null {
  return Object.hasOwn(STUDENT_PROJECTS, id) ? STUDENT_PROJECTS[id] : null;
}

export const PAYMENT_PURPOSES = ['student-project', 'custom'] as const;
export type PaymentPurpose = (typeof PAYMENT_PURPOSES)[number];

export const PAYMENT_PURPOSE_LABELS: Record<PaymentPurpose, string> = {
  'student-project': 'Student / college project',
  custom: 'Custom payment',
};

export const SUPPORTED_CURRENCIES = ['INR'] as const;

/** Razorpay rejects orders below ₹1. */
export const MIN_ORDER_AMOUNT_PAISE = 100;
